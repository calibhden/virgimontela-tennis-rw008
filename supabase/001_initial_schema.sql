create extension if not exists btree_gist with schema extensions;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'pending'
    check (role in ('pending', 'scheduling_admin', 'global_admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.courts (
  id text primary key check (id in ('A', 'B')),
  name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.players (
  id bigint generated by default as identity primary key,
  full_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index players_full_name_unique
  on public.players (lower(trim(full_name)));

create table public.player_private (
  player_id bigint primary key references public.players(id) on delete cascade,
  residence text,
  booking_reputation text not null default 'Clear',
  phone text,
  in_whatsapp boolean,
  updated_at timestamptz not null default now()
);

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  court_id text not null references public.courts(id),
  title text not null,
  booking_type text not null
    check (booking_type in ('mabar_warga', 'private', 'non_warga', 'incidental', 'basket')),
  priority smallint check (priority between 1 and 3),
  resident_ratio text not null default 'not_applicable'
    check (resident_ratio in ('gte_50', 'lt_50', 'not_applicable')),
  start_at timestamptz not null,
  end_at timestamptz not null,
  status text not null default 'confirmed'
    check (status in ('confirmed', 'cancelled', 'no_show')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bookings_valid_duration check (end_at > start_at),
  constraint bookings_operating_hours check (
    (start_at at time zone 'Asia/Jakarta')::time >= time '05:00'
    and (end_at at time zone 'Asia/Jakarta')::time <= time '22:00'
    and (start_at at time zone 'Asia/Jakarta')::date = (end_at at time zone 'Asia/Jakarta')::date
  ),
  constraint bookings_no_overlap exclude using gist (
    court_id with =,
    tstzrange(start_at, end_at, '[)') with &&
  ) where (status = 'confirmed')
);

create index bookings_start_at_idx on public.bookings (start_at);
create index bookings_court_start_idx on public.bookings (court_id, start_at);

create table public.booking_players (
  booking_id uuid not null references public.bookings(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  is_resident boolean not null default true,
  primary key (booking_id, player_id)
);

create table public.audit_events (
  id bigint generated always as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  entity_type text not null,
  entity_id text not null,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

