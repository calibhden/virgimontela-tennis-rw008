create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    coalesce(new.email, ''),
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role
  from public.profiles
  where id = (select auth.uid()) and is_active = true
  limit 1;
$$;

create or replace function public.can_schedule()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() in ('scheduling_admin', 'global_admin'), false);
$$;

create or replace function public.is_global_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() = 'global_admin', false);
$$;

create or replace function public.set_user_access(
  target_user_id uuid,
  new_role text,
  new_is_active boolean default true
)
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.profiles;
begin
  if not public.is_global_admin() then
    raise exception 'Only global administrators can change access';
  end if;

  if new_role not in ('pending', 'scheduling_admin', 'global_admin') then
    raise exception 'Invalid role';
  end if;

  update public.profiles
  set role = new_role, is_active = new_is_active, updated_at = now()
  where id = target_user_id
  returning * into result;

  if result.id is null then
    raise exception 'User profile not found';
  end if;

  insert into public.audit_events (actor_id, entity_type, entity_id, action, detail)
  values ((select auth.uid()), 'profile', target_user_id::text, 'set_user_access', jsonb_build_object('role', new_role, 'is_active', new_is_active));

  return result;
end;
$$;

create or replace function public.audit_booking_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  changed_id text;
begin
  if tg_op = 'DELETE' then
    changed_id := old.id::text;
  else
    changed_id := new.id::text;
  end if;
  insert into public.audit_events (actor_id, entity_type, entity_id, action, detail)
  values (
    (select auth.uid()),
    'booking',
    changed_id,
    lower(tg_op),
    case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

create trigger bookings_audit
after insert or update or delete on public.bookings
for each row execute function public.audit_booking_change();

